/**
 * Helpers shared by the local SEO and AI plugins.
 */
const path = require('path')

const HOSTNAME = 'https://rafaelneto.dev'

// Social card of the pages that are not posts (home, about, post lists, tags), drawn by og-images.js
const SITE_CARDS = {
  es: { path: '/images/og/site.png', tagline: 'Apuntes de un programador Full Stack' },
  en: { path: '/images/og/site-en.png', tagline: 'Notes from a Full Stack developer' }
}

// Public profile, taken from the "Sobre mí" page (blog/README.md).
const PERSON = {
  '@type': 'Person',
  '@id': `${HOSTNAME}/#person`,
  name: 'Rafael Neto',
  url: `${HOSTNAME}/`,
  jobTitle: 'Full Stack Developer',
  knowsAbout: ['Software architecture', '.NET', 'TypeScript', 'JavaScript', 'Angular', 'HTML', 'CSS'],
  sameAs: [
    'https://www.linkedin.com/in/rrneto',
    'https://github.com/rneto',
    'https://x.com/rneto',
    'https://app.pluralsight.com/profile/rneto',
    'https://www.hackerrank.com/rneto',
    'https://stackblitz.com/@rneto'
  ]
}

const POST_PATH = /^\/(en\/)?blog\/(?!page\/)[^/]+\/$/
// Language switcher links: `Español | [English](/en/...)` on Spanish pages, `[Español](/...) | English` on English ones
const ENGLISH_LINK = /\[English\]\((\/en\/[^)\s]*)\)/
const SPANISH_LINK = /\[Español\]\((\/(?!en\/)[^)\s]*)\)/

const isEnglish = pagePath => pagePath.startsWith('/en/')
const isPost = page => Boolean(page.frontmatter && page.frontmatter.date) && POST_PATH.test(page.path || '')

function parseDate (value) {
  if (!value) return undefined
  if (value instanceof Date) return isNaN(value) ? undefined : value
  const short = String(value).match(/^(\d{4})-(\d{1,2})-(\d{1,2})$/)
  const date = short ? new Date(Date.UTC(+short[1], short[2] - 1, +short[3])) : new Date(value)
  return isNaN(date) ? undefined : date
}

function toIso (value) {
  const date = parseDate(value)
  return date && date.toISOString()
}

function modifiedTime (frontmatter) {
  const meta = (frontmatter.meta || []).find(item => item.property === 'article:modified_time')
  return meta ? meta.content : undefined
}

const publishedIso = page => toIso(page.frontmatter.date)
const modifiedIso = page => toIso(modifiedTime(page.frontmatter) || page.frontmatter.date)
// Short text for search results and structured data: `description` if the post has one.
const summaryOf = page => page.frontmatter.description || page.frontmatter.summary || ''
// Longer text for AI indexes and Markdown copies: the post-list `summary` first.
const longSummaryOf = page => page.frontmatter.summary || page.frontmatter.description || ''

// Lowercased target of the page's language switcher, or undefined when it is missing or commented out.
function switcherLink (page) {
  const content = (page._content || '').replace(/<!--[\s\S]*?-->/g, '')
  // In extendPageData the permalink is not built yet, so also look at the source folder (_en/)
  const english = isEnglish(page.path || '') || (page.regularPath || '').startsWith('/_en/')
  const match = english ? content.match(SPANISH_LINK) : content.match(ENGLISH_LINK)
  return match ? match[1].toLowerCase() : undefined
}

// Real path of the translated page, or undefined when the switcher is missing,
// commented out, or points to a page that does not exist.
function counterpartPath (page, pathsByLowerCase) {
  const link = switcherLink(page)
  return link ? pathsByLowerCase.get(link) : undefined
}

const markdownPath = pagePath => pagePath.replace(/\/$/, '.md')

function htmlFile (outDir, pagePath) {
  const decoded = decodeURIComponent(pagePath)
  return decoded.endsWith('/')
    ? path.join(outDir, decoded, 'index.html')
    : path.join(outDir, decoded)
}

const pathIndex = pages => new Map(pages.filter(page => page.path).map(page => [page.path.toLowerCase(), page.path]))

// Social card generated by og-images.js: /blog/my-post/ -> /images/og/blog/my-post.png
const ogImagePath = page => `/images/og${page.path.replace(/\/$/, '')}.png`

const siteCard = page => SITE_CARDS[isEnglish(page.path || '') ? 'en' : 'es']

// Absolute URL of the image shown when a page is shared: the post's own `image`, its generated card,
// or the site card in the page's language
const shareImage = page => {
  if (page.frontmatter && page.frontmatter.image) return `${HOSTNAME}${page.frontmatter.image}`
  return `${HOSTNAME}${isPost(page) ? ogImagePath(page) : siteCard(page).path}`
}

// Text alternative of that image: the page title, or the name and tagline shown on the site card
const shareImageAlt = page => isPost(page) || (page.frontmatter && page.frontmatter.image)
  ? page.title
  : `Rafael Neto: ${siteCard(page).tagline}`

const postsNewestFirst = pages => pages
  .filter(isPost)
  .sort((a, b) => parseDate(b.frontmatter.date) - parseDate(a.frontmatter.date))

module.exports = {
  HOSTNAME,
  SITE_CARDS,
  PERSON,
  isEnglish,
  isPost,
  parseDate,
  toIso,
  modifiedTime,
  publishedIso,
  modifiedIso,
  summaryOf,
  longSummaryOf,
  switcherLink,
  counterpartPath,
  markdownPath,
  htmlFile,
  pathIndex,
  ogImagePath,
  shareImage,
  shareImageAlt,
  postsNewestFirst
}
